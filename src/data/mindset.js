export const getMindsetLesson = (lessonId) => mindsetLessons.find(l => l.id === lessonId)

export const getMindsetUnits = () => {
  const units = {}
  for (const lesson of mindsetLessons) {
    if (!units[lesson.unit]) units[lesson.unit] = []
    units[lesson.unit].push(lesson)
  }
  return units
}
