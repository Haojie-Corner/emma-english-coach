export const getAllScenes = () => sceneCategories.flatMap(cat => cat.scenes)

export const getScene = (sceneId) => {
  for (const cat of sceneCategories) {
    const scene = cat.scenes.find(s => s.id === sceneId)
    if (scene) return { ...scene, categoryId: cat.id, categoryName: cat.name }
  }
  return null
}

export const getCategory = (categoryId) => sceneCategories.find(c => c.id === categoryId)
